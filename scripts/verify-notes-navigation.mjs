import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import vm from "node:vm";

const bundle = readFileSync(new URL("../.quartz/plugins/explorer/dist/index.js", import.meta.url), "utf8");
const source = bundle.match(/mapFn: (\(node\) => \{\s*\/\* notes-navigation:start \*\/[\s\S]*?\/\* notes-navigation:end \*\/\s*\}),/)[1];
const map = vm.runInNewContext(`(${source})`);
const sortSource = bundle.match(/sortFn: (\(a2, b2\) => \{\s*\/\* source-order:start \*\/[\s\S]*?\/\* source-order:end \*\/\s*\}),/)[1];
const sort = vm.runInNewContext(`(${sortSource})`);
const node = (slug) => ({ slugSegments: [slug], slugSegment: slug, children: [] });
const root = { slugSegments: [], children: [node("研究"), node("笔记-notes@ustc"), node("笔记"), node("首页")] };
map(root);
root.children.sort(sort);
assert.deepEqual(root.children.map(child => child.slugSegment), ["首页", "笔记", "研究"]);
map(root);
assert.equal(root.children.length, 3);
const html = readFileSync(new URL("../public/笔记.html", import.meta.url), "utf8");
assert.ok(html.includes('class="toc'), "Article table of contents must remain");
assert.ok(html.includes("notes-navigation:start"), "Built page must include sidebar filter");
console.log("PASS: duplicate notes tree hidden, primary links retained in order, article TOC retained.");
